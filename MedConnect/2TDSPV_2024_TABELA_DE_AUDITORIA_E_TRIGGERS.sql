--Tabela para auditória

CREATE TABLE T_MDCT_AUDITORIA (
    ID_AUDITORIA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OPERACAO VARCHAR2(10),
    NOME_TABELA VARCHAR2(30),
    COLUNAS_ANTERIORES CLOB,
    COLUNAS_NOVAS CLOB,
    USUARIO VARCHAR2(30),
    DATA_OPERACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Trigger para INSERT
CREATE OR REPLACE TRIGGER trg_audit_insert_cliente
AFTER INSERT ON T_MDCT_CLIENTE
FOR EACH ROW
BEGIN
    BEGIN
        INSERT INTO T_MDCT_AUDITORIA (
            OPERACAO, NOME_TABELA, COLUNAS_ANTERIORES, COLUNAS_NOVAS, USUARIO
        )
        VALUES (
            'INSERT',
            'T_MDCT_CLIENTE',
            NULL, 
            '{"ID_CLIENTE": "' || :NEW.ID_CLIENTE || '", "NM_CLIENTE": "' || :NEW.NM_CLIENTE || '", "NR_CPF": "' || :NEW.NR_CPF || '", "NM_RG": "' || :NEW.NM_RG || '", "LG_CLIENTE": "' 
            || :NEW.LG_CLIENTE || '", "SH_CLIENTE": "' || :NEW.SH_CLIENTE || '", "DT_NASCIMENTO": "' || TO_CHAR(:NEW.DT_NASCIMENTO, 'YYYY-MM-DD') || '", "DT_CADASTRO": "' 
            || TO_CHAR(:NEW.DT_CADASTRO, 'YYYY-MM-DD') || '", "NM_USUARIO": "' 
            || :NEW.NM_USUARIO || '"}',
            SYS_CONTEXT('USERENV', 'SESSION_USER')
        );
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('Erro ao auditar INSERT: ' || SQLERRM);
    END;
END;
/

